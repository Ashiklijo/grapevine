// Writes docs/TESTNET.md from what is on chain and from the last end-to-end run.
// Read-only. Run it after scripts/deploy.mjs and scripts/e2e.mjs.
//
//   node scripts/report.mjs
import fs from "node:fs";
import path from "node:path";
import { RPCS, NETWORK, ROOT, accountUrl, balanceOf, deployment, toNear, txUrl, view } from "./lib.mjs";

const d = deployment();
const e2eFile = path.join(ROOT, "deployments", "testnet-e2e.json");
const e2e = fs.existsSync(e2eFile) ? JSON.parse(fs.readFileSync(e2eFile, "utf8")) : null;

async function account(id) {
  const res = await fetch(RPCS[NETWORK][1], {
    method: "POST",
    headers: { "content-type": "application/json" },
    body: JSON.stringify({ jsonrpc: "2.0", id: 1, method: "query", params: { request_type: "view_account", finality: "final", account_id: id } }),
  });
  return (await res.json()).result;
}

const link = (id) => `[\`${id}\`](${accountUrl(id)})`;
const tx = (hash, label = "transaction") => (hash ? `[${label}](${txUrl(hash)})` : "");
const board = await view(d.contract, "get_board", { dao: d.dao });
const totals = await view(d.contract, "totals");
const policy = await view(d.dao, "get_policy");
const role = policy.roles.find((r) => r.kind?.Group?.includes(d.contract));
const code = await account(d.contract);
const quests = await view(d.contract, "list_quests", { dao: d.dao, from_index: 0, limit: 100 });
const people = await view(d.contract, "list_people", { dao: d.dao, from_index: 0, limit: 100 });
const cfg = board.config;
const days = Math.round(Number(cfg.period_ns) / 86_400e9);

const out = [];
out.push("# Testnet results", "");
out.push(`Generated by \`node scripts/report.mjs\` on ${new Date().toISOString().slice(0, 16).replace("T", " ")} UTC, from what is on chain and from the last run of \`scripts/e2e.mjs\`. Everything here is NEAR testnet. Test tokens only.`, "");

out.push("## What is deployed", "");
out.push("| What | Account |", "|---|---|");
out.push(`| The Grapevine contract, version ${await view(d.contract, "version")} | ${link(d.contract)} |`);
out.push(`| The demo DAO, made by the unmodified Sputnik factory \`${d.factory}\` | ${link(d.dao)} |`);
out.push(`| The account that paid for everything | ${link(d.hq)} |`);
out.push(`| Stewards: the DAO's council | ${board.stewards.map(link).join(", ")} |`);
out.push(`| The keeper, which only makes calls anyone may make | ${link(d.people.keeper)} |`, "");
out.push(`- The contract's code hash on chain is \`${code.code_hash}\`. Build it yourself with \`cargo near build non-reproducible-wasm --no-abi\` and compare the bs58 checksum it prints. A non-reproducible build can differ between machines; the source in this repository is what was built.`);
out.push(`- The copy is bound to one DAO: \`dao()\` answers \`${await view(d.contract, "dao")}\`.`);
const daoAccount = await account(d.dao);
const daoSpendable = BigInt(daoAccount.amount) - BigInt(daoAccount.storage_usage) * 10n ** 19n;
out.push(`- The treasury can spend ${toNear(daoSpendable.toString(), 2)} NEAR. The DAO account holds ${toNear(daoAccount.amount, 2)} NEAR, and its own code and storage lock the rest. The contract holds ${toNear(await balanceOf(d.contract), 2)} NEAR, of which ${toNear(board.float, 3)} is spare float and the rest is locked by its storage.`, "");

out.push("## How it was installed", "");
out.push("Two ordinary proposals on the DAO, each passed by the council's own two votes.", "");
out.push("| Step | Proposal | Transactions |", "|---|---|---|");
const votes = (prefix) =>
  Object.entries(d.txs ?? {})
    .filter(([k]) => k.startsWith(prefix))
    .map(([k, h]) => tx(h, k.replace(prefix, "vote by ")))
    .join(", ");
out.push(`| Add the role \`${role?.name}\`: ${role?.permissions.map((p) => `\`${p}\``).join(", ")} | #${d.proposals?.role ?? "?"} | ${votes("install_role_vote_")} |`);
out.push(`| Call \`create_board\` with the rules below and a 0.3 NEAR float | #${d.proposals?.board ?? "?"} | ${votes("create_board_vote_")} |`, "");
out.push("The rules the DAO set:", "");
out.push("| Rule | Value |", "|---|---|");
out.push(`| The doer's share | ${cfg.doer_bps / 100}% |`);
out.push(`| The share of the account that told the doer | ${cfg.relay_bps / 100}%, halving for each step back, for at most ${cfg.max_hops} accounts |`);
out.push(`| Shares below this are not paid | ${toNear(cfg.min_cut)} NEAR |`);
out.push(`| Earned limit | ${toNear(cfg.step)} NEAR per point, up to ${toNear(cfg.ceiling)} NEAR per period, never above what a second steward has approved for that account |`);
out.push(`| Above this, the DAO's ordinary vote | ${toNear(cfg.countersign_cap)} NEAR |`);
out.push(`| One steward can open | ${toNear(cfg.quest_cap)} NEAR per quest, ${toNear(cfg.period_cap)} NEAR per ${days} days in all |`, "");

if (e2e) {
  out.push("## The live checks", "");
  out.push(`\`scripts/e2e.mjs\` ran on ${e2e.ran_at.slice(0, 16).replace("T", " ")} UTC against the deployed code: **${e2e.passed} of ${e2e.checks.length} checks passed**${e2e.failed ? `, ${e2e.failed} failed` : ""}. Every check is a real transaction or a real read. A refusal is the contract's own, and its link opens the failed transaction.`, "");
  out.push("| | Check | Detail | |", "|---|---|---|---|");
  for (const c of e2e.checks) {
    const detail = String(c.detail ?? "").replace(/\|/g, "\\|").replace(/\s+/g, " ").slice(0, 150);
    out.push(`| ${c.ok ? "pass" : "**FAIL**"} | ${c.name} | ${detail} | ${c.tx ? `[tx](${c.tx})` : ""} |`);
  }
  out.push("");
  const p = e2e.evidence?.proposals ?? {};
  if (Object.keys(p).length) {
    out.push("Proposals on the DAO that those checks produced, to look up in any Sputnik interface:", "");
    out.push(Object.entries(p).map(([k, v]) => `\`${k}\`: #${v}`).join(", "), "");
  }
} else {
  out.push("## The live checks", "", "`scripts/e2e.mjs` has not been run against this deployment yet.", "");
}

out.push("## The board now", "");
out.push(`${totals.quests} quests, ${totals.payouts} payments decided, ${toNear(totals.paid)} NEAR paid from the treasury, ${people.filter((x) => x.points > 0).length} accounts with a record.`, "");
out.push("| # | Quest | Reward | Status | On the vine | Paid |", "|---|---|---|---|---|---|");
for (const q of quests) {
  out.push(`| ${q.id} | ${q.title.replace(/\|/g, "\\|")} | ${toNear(q.reward)} | ${q.status} | ${q.links} | ${toNear(q.paid)} to ${q.payouts.length} |`);
}
out.push("");

out.push("## What did not run", "");
out.push("- **Expired proposals.** A testnet proposal takes seven days to expire, so the path that finalizes one is covered by the rule tests and by the contract's tests on near-sdk's mocked runtime (`cargo test -p grapevine`), not by a live run.");
out.push("- **A failed transfer.** The retry after a transfer fails on the DAO is covered the same way: by the rule tests and the mocked-runtime tests, not by a live run.");
out.push("- **Mainnet.** Nothing was deployed or signed on mainnet. near.social's own indexer and app are mainnet-only, so posts here are the same `social-kv/1` writes on testnet, read back from FastNEAR's public testnet KV API.");
out.push("- **Trezu.** Its hosted app is mainnet-only. The proposals use the description format its parser reads, and that was checked by reading its source, not by running it.");
out.push("- **A real wallet in the browser.** The site is read-only without the demo server. `scripts/try.mjs` is the way in with your own testnet account.", "");

fs.writeFileSync(path.join(ROOT, "docs", "TESTNET.md"), out.join("\n"));
console.log(`docs/TESTNET.md written: ${e2e ? `${e2e.passed}/${e2e.checks.length} checks` : "no e2e run yet"}, ${quests.length} quests`);
